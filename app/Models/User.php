        'email',
        'password',
        'license_number',
        'license_code',
        'license_image_path',
        'license_image_data',
        'license_image_mime',
        'driver_approval_status',
    ];

    /**
     * The attributes that should be hidden for serialization.
     *
     * @var array<int, string>
     */
